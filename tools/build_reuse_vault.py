"""Render navigation documents from existing ledgers without changing their authority."""
from __future__ import annotations

from collections import defaultdict
from functools import lru_cache
import hashlib
import json
import os
import posixpath
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
PLAN = Path('data/verification/category2-edge-work-plan.json')
MARKER = '<!-- generated by tools/build_reuse_vault.py; authority remains in existing ledgers -->'
REUSE_INDEX = Path('vaults/재사용/인덱스.md')
ID_TABLE = '\n## 원조항 ID로 찾기\n\n| 원조항 ID | 실제 경로 |\n|---|---|\n'


def plain(value):
    if isinstance(value, (list, tuple)):
        return '; '.join(plain(item) for item in value)
    if isinstance(value, dict):
        return json.dumps(value, ensure_ascii=False).replace('|', '\\|')
    return str(value).replace('\n', ' ').replace('|', '\\|')


@lru_cache(maxsize=8192)
def link(label, target, note):
    """Markdown paths are relative to the document, including references outside vaults."""
    path, sep, fragment = str(target).partition('#')
    relative = (os.path.relpath(ROOT / path, ROOT / note.parent).replace('\\', '/')
                if os.path.isabs(path) or os.path.splitdrive(path)[0]
                else posixpath.relpath(path.replace('\\', '/'), note.parent.as_posix()))
    return f'[{plain(label)}](<{relative}{sep}{fragment}>)'


def section(title, values):
    if not values:
        return []
    return ['', f'## {title}', ''] + [f'- {plain(v)}' for v in values]


def render_route(name, route, rows, foundation_ids):
    """Keep consumer conditions and navigation; verification stays in its ledger."""
    if not re.fullmatch(r'[A-Za-z0-9_-]+', name):
        raise ValueError(f'Unsafe route filename: {name}')
    note = Path(f'vaults/재사용/{name}.md')
    reference = str(PLAN) + '#post_foundation_reuse.itemized_audit.routes/' + name
    body = [f'# {name}', '', MARKER, '',
            '소비자 고유 조건과 실행 연결. 검증 결과·로그·계수는 정본 기록을 따른다.', '',
            plain(route.get('behavior', '')), '',
            '정본: ' + link('실제 경로 점검 기록', reference, note)]
    body += section('실제 실행 경로', route.get('native_paths', []))
    body += ['', '## 연결된 공통 기반', '']
    for uid in route.get('foundation_ids', []):
        if uid not in foundation_ids:
            raise ValueError(f'Unknown original foundation: {uid}')
        body.append('- ' + link(uid, f'vaults/공통기반/{uid}.md', note))
    body += section('관련 검사 모듈', [f'`{v}`' for v in route.get('required_test_modules', [])])
    body += ['', '## 재사용한 검증 근거', '',
             link('검증 로그·해시·실행 결과', reference + '/evidence', note), '',
             '## 원조항별 연결', '', '| 원조항 ID | 이름·원래 의무 |', '|---|---|']
    for row in rows:
        body.append(f'| {plain(row["id"])} | {plain(row.get("name", ""))} |')
    body += ['', '같은 경로라도 각 원조항의 고유 조건·예외는 유지한다. 미완료 엣지를 이 행들에 자동 합류시키거나 완료로 간주하지 않는다.']
    return '\n'.join(body) + '\n'


def render_reuse_index(routes, items, grouped, index_routes):
    lines = ['# 기존 구현의 실제 재사용 경로', '', MARKER, '',
             '탐색용 사본. 아래 상태와 검사는 정본에 기록된 기존 근거이며 새 검증이 아니다.', '',
             '한 행은 기존 원조항 ID다. 초기 95개와 명시적 추가 항목의 소속·완료 판정은 기존 장부를 따른다. 본 문서를 생성해도 구현 완료나 검사 완료가 추가되지 않는다.', '',
             '| 실제 경로 | 연결 조항 수 | 동작 |', '|---|---:|---|']
    for name, route in routes.items():
        if not re.fullmatch(r'[A-Za-z0-9_-]+', name):
            raise ValueError(f'Unsafe route filename: {name}')
        note = Path(f'vaults/재사용/{name}.md')
        behavior = (link('고유 조건·예외', note.as_posix() + '#' + name, REUSE_INDEX)
                    if name in index_routes else plain(route.get('behavior', '정본 참조')))
        lines.append(f'| {link(name, note, REUSE_INDEX)} | {len(grouped[name])} | {behavior} |')
    lines += ['', '## 원조항 ID로 찾기', '', '| 원조항 ID | 실제 경로 |', '|---|---|']
    for row in items:
        lines.append(f'| {plain(row["id"])} | {link(row["route"], "vaults/재사용/" + row["route"] + ".md", REUSE_INDEX)} |')
    return '\n'.join(lines) + '\n'


def render(plan, root=ROOT, *, update_routes=True, index_only=False):
    from reuse_navigation import has_legacy_generated_body

    f = plan['foundation_discovery']
    frozen = f['foundation_freeze']
    ids = frozen['unit_ids']
    units = {v['id']: v for v in frozen['units']}
    progress = f['common_foundation_progress']['units']
    scopes = {v['id']: v for v in f['foundation_execution_plan']['units']}
    drafts = {v['id']: v for v in f['foundation_unit_drafts']['units']}
    if len(ids) != 57 or len(set(ids)) != 57 or set(ids) != set(units) or not set(ids) <= set(progress):
        raise ValueError('Original 57-unit contract is inconsistent; do not invent replacements.')
    audit = plan['post_foundation_reuse']['itemized_audit']
    routes = audit['routes']
    items = audit['items']
    # A short reference is safe only when the full exact contract and its
    # heading already exist in the representative consumer. Keep differing or
    # unavailable source summaries in place instead of treating them as aliases.
    compact_routes = set()
    index_routes = set()
    for name, route in routes.items():
        if not re.fullmatch(r'[A-Za-z0-9_-]+', name):
            continue
        behavior = plain(route.get('behavior', ''))
        representative = Path(root) / 'vaults' / '재사용' / f'{name}.md'
        if len(behavior) >= 300:
            supported = False
            if update_routes and not representative.exists() and not representative.is_symlink():
                # The missing route will be generated below with this exact heading and behavior.
                supported = True
            elif representative.is_file():
                current = representative.read_text(encoding='utf-8')
                if (behavior in current and re.search(r'(?m)^# ' + re.escape(name) + r'\s*$', current)
                        or update_routes and MARKER in current and has_legacy_generated_body(
                            Path(f'vaults/재사용/{name}.md'), current)):
                    supported = True
            if supported:
                index_routes.add(name)
                if len(route.get('foundation_ids', [])) >= 4:
                    compact_routes.add(name)
    grouped = defaultdict(list)
    for row in items:
        if row['route'] not in routes:
            raise ValueError(f"Unknown existing route: {row['route']}")
        grouped[row['route']].append(row)
    if index_only:
        return {REUSE_INDEX: render_reuse_index(routes, items, grouped, index_routes)}
    docs = {}
    header = [MARKER, '', '탐색용 사본. 아래 상태와 검사는 정본에 기록된 기존 근거이며 새 검증이 아니다.']
    foundation_index = Path('vaults/공통기반/인덱스.md')
    index = ['# 원래 공통 기반 57개', '', *header, '',
             '필요한 ID만 골라 문서를 읽는다. 문서의 연결은 재사용 후보를 찾는 단서다. 실제 호출 경로와 조건·예외가 맞는지는 해당 구현에서 확인한다.', '',
             '| ID | 기존 의미 | 문서 |', '|---|---|---|']
    for uid in ids:
        unit, done, scope = units[uid], progress[uid], scopes[uid]
        note = Path(f'vaults/공통기반/{uid}.md')
        title = drafts.get(uid, {}).get('title', uid)
        index.append(f'| {uid} | {plain(unit["observable_outcome"])} | {link(title, note, foundation_index)} |')
        lines = [f'# {uid} — {title}', '', *header, '',
                 f'원래 의미: {unit["observable_outcome"]}', '',
                 f'기존 완료 상태: `{done["status"]}`. 검증 기록 시점: `{done.get("verified_at", "정본 참조")}`.', '',
                 f'계약 정본: {link("기반 동결 계약", str(PLAN) + "#foundation_discovery.foundation_freeze.units/" + uid, note)}', '',
                 f'반드시 지킬 예외·부정 조건: {unit.get("negative_acceptance", "동결 계약 참조")}', '',
                 f'구현 범위: {scope.get("shared_runtime_work", "기존 구현 기록 참조")}', '',
                 f'선언·입력 조건: {scope.get("declaration_and_validation_scope", "기존 구현 기록 참조")}']
        targets = scope.get('reuse_and_integration_targets', [])
        lines += ['', '## 기존 실행 진입점', '']
        for target in targets:
            lines.append(f'- {link(target["file"], target["file"], note)} :: `{target["symbol"]}`')
        lines += ['', '## 이미 구현된 처리와 근거', '']
        for req in done.get('requirements', []):
            lines += [f'- 요구: {plain(req.get("requirement", "정본 참조"))}',
                      f'  - 처리: `{plain(req.get("implementation", "정본 참조"))}`',
                      f'  - 근거: {plain(req.get("evidence", "정본 참조"))}']
        lines += section('기존 변경 기록', done.get('changes', []))
        lines += ['', '## 관련 검사', '']
        for check in done.get('checks', []):
            log = check.get('log')
            ref = link(log, log, note) if log else '정본 기록 참조'
            if 'result' in check:
                result = plain(check['result'])
            elif 'passed' in check:
                result = f'통과 기록: {plain(check["passed"])}'
            else:
                result = '결과 미기록; 정본 참조'
            lines.append(f'- `{check.get("suite", "정본 검사")}` — {result}; {ref}')
        lines += ['', '## 의존 기반과 실제 재사용 사례', '']
        for dep in scope.get('dependency_ids', []):
            lines.append('- ' + link(dep, f'vaults/공통기반/{dep}.md', note))
        for name, route in routes.items():
            if uid in route.get('foundation_ids', []):
                target = f'vaults/재사용/{name}.md'
                label = name + ': ' + plain(route.get('behavior', ''))
                if name in compact_routes:
                    target += '#' + name
                    label = name + ' — 고유 조건·예외'
                lines.append('- ' + link(label, target, note))
        if uid in plan['latest_reassessment'].get('stamina_partial', {}).get('foundation_ids', []):
            lines.append('- ' + link('미완료 소비자: 스테미너·숨돌리기', 'vaults/작업/스테미너.md', note))
        lines += ['', '## 사용 전 확인', '',
                  '위 입력·시작 사건·대상·소유·중첩·수명·소비·예외가 현재 규칙과 맞는지 비교한다. 과거 파일 해시나 함수 존재만으로 현재 실행 경로 재사용을 확정하지 않는다. 관련 변경이 있다면 그 경계의 검사를 갱신한다. 전체 검사를 매번 반복할 의무는 아니다.', '',
                  '정본 상세: ' + link('구현 및 검증 기록', str(PLAN) + '#foundation_discovery.common_foundation_progress.units/' + uid, note)]
        docs[note] = '\n'.join(lines) + '\n'
    docs[foundation_index] = '\n'.join(index) + '\n'

    for name, route in routes.items():
        note = Path(f'vaults/재사용/{name}.md')
        docs[note] = render_route(name, route, grouped[name], units)
    docs[REUSE_INDEX] = render_reuse_index(routes, items, grouped, index_routes)
    return docs


def preserve_reuse_index(current, generated):
    """Replace only the generated tables, retaining the manual preface and log."""
    newline = '\r\n' if '\r\n' in current else '\n'
    if '\r' in current.replace('\r\n', '') or (newline == '\r\n' and '\n' in current.replace('\r\n', '')):
        raise ValueError('Refusing mixed reuse index line endings.')
    current = current.replace('\r\n', '\n')
    if (current.count(MARKER) != 1 or generated.count(MARKER) != 1
            or current.count(ID_TABLE) != 1 or generated.count(ID_TABLE) != 1):
        raise ValueError('Refusing to regenerate a reuse index without unique boundaries.')
    prefix = current.split(MARKER, 1)[0]
    if not prefix.startswith('# 기존 구현의 실제 재사용 경로\n'):
        raise ValueError('Refusing to regenerate a reuse index without its heading.')
    old_body = current.split(MARKER, 1)[1].split(ID_TABLE, 1)[0]
    new_body = generated.split(MARKER, 1)[1].split(ID_TABLE, 1)[0]
    without_routes = lambda body: [line for line in body.splitlines() if not line.startswith('| [')]
    if without_routes(old_body) != without_routes(new_body):
        raise ValueError('Refusing to replace handwritten content inside generated route rows.')
    route_keys = lambda body: {tuple(line.split(' | ', 2)[:2]) for line in body.splitlines()
                               if line.startswith('| [')}
    if not route_keys(old_body) <= route_keys(new_body):
        raise ValueError('Refusing to discard an unrecognized reuse route row.')
    tail = current.split(ID_TABLE, 1)[1].splitlines(keepends=True)
    rows = []
    while tail and tail[0].startswith('| '):
        rows.append(tail.pop(0))
    generated_rows = set(generated.split(ID_TABLE, 1)[1].splitlines(keepends=True))
    if not rows or not set(rows) <= generated_rows:
        raise ValueError('Refusing to discard an unrecognized reuse index row.')
    if tail and tail[0].strip():
        raise ValueError('Refusing to absorb an unbounded reuse index appendix.')
    return (prefix + MARKER + generated.split(MARKER, 1)[1] + ''.join(tail)).replace('\n', newline)


def refresh_reuse_index(root=ROOT):
    """Update this index alone, leaving all other generated and handwritten notes."""
    root = Path(root)
    source = root / PLAN
    authority = source.read_bytes()
    path = root / REUSE_INDEX
    original = path.read_bytes() if path.exists() else None
    generated = render(json.loads(authority.decode('utf-8-sig')), root=root,
                       update_routes=False, index_only=True)[REUSE_INDEX]
    content = preserve_reuse_index(original.decode('utf-8'), generated) if original is not None else generated
    if source.read_bytes() != authority or (path.read_bytes() if path.exists() else None) != original:
        raise RuntimeError('Index or authority changed during rendering; refusing to publish.')
    changed = original != content.encode('utf-8')
    if changed:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content.encode('utf-8'))
    return {'changed': int(changed), 'authority_sha256': hashlib.sha256(authority).hexdigest()}


def build(root=ROOT):
    from reuse_navigation import (CONTRACTS, has_legacy_generated_body,
                                  preserve_additions, refresh, without_links)

    root = Path(root)
    source = root / PLAN
    before = source.read_bytes()
    plan = json.loads(before.decode('utf-8-sig'))
    docs = render(plan, root=root)
    # Never replace handwritten user instructions, entry points or work notes.
    preserved_route_bodies = []
    for relative, content in docs.items():
        path = root / relative
        if not path.exists():
            continue
        current = path.read_bytes().decode('utf-8')
        is_route = relative.parent == Path('vaults/재사용') and relative.name != '인덱스.md'
        # Keep only the existing, note-specific guarantee notice and blank lines
        # before the H1; arbitrary or duplicate preambles need inspection.
        clean = without_links(current)
        notice = (f'> 현재 보장·전제·범위 밖·소비자 검사 책임: [{relative.stem}]'
                  f'(../공통보장/{relative.stem}.md). 기존 완료/검사 기록은 당시 범위의 이력이다.')
        notice_pattern = re.escape(notice)
        if relative == Path('vaults/공통기반/인덱스.md'):
            notice_pattern = r'> 현재[0-9]+' + re.escape(
                '의 [실제 보장·전제·한계](../공통보장/인덱스.md)와 '
                '[검사 재사용 책임](../공통보장/검사재사용과축소.md)을 따른다. '
                '아래 완료·탐색 연결이 모든 소비자의 검증을 대체하지 않는다.')
        blanks = r'(?:[ \t]*\r?\n)*'
        heading = re.match('(' + blanks + '(?:' + notice_pattern + r'\r?\n'
                           + blanks + r')?)# [^\r\n]+\r?\n', clean)
        if is_route and (MARKER not in current or not has_legacy_generated_body(relative, current)):
            # A verified route may be documented by hand before it is added to the
            # legacy itemized audit. Compatibility notes can also retain the old
            # generator marker without using its table/footer shape. Keep either
            # body and let reuse_navigation refresh only its bounded backlink block.
            if heading is None:
                raise ValueError(f'Refusing to adopt a handwritten route without a heading boundary: {path}')
            preserved_route_bodies.append(relative)
            continue
        if MARKER not in current:
            raise ValueError(f'Refusing to overwrite a handwritten document: {path}')
        if heading is None:
            raise ValueError(f'Refusing to regenerate a document without a heading boundary: {path}')
        docs[relative] = (preserve_reuse_index(current, content) if relative == REUSE_INDEX
                          else preserve_additions(relative, current, heading.group(1) + content))
    changed = 0
    for relative, content in docs.items():
        if relative in preserved_route_bodies:
            continue
        path = root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists() or path.read_bytes() != content.encode('utf-8'):
            path.write_bytes(content.encode('utf-8'))
            changed += 1
    if source.read_bytes() != before:
        raise RuntimeError('Authority changed during rendering; inspect before using generated notes.')
    result = {'documents': len(docs), 'changed': changed,
              'preserved_route_bodies': [relative.as_posix() for relative in preserved_route_bodies],
              'authority_sha256': hashlib.sha256(before).hexdigest()}
    if (root / CONTRACTS).is_file():
        result['navigation'] = refresh(root)
    return result


if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--navigation', action='store_true', help='Refresh short links without replacing note bodies.')
    mode.add_argument('--index', action='store_true', help='Refresh only the reuse route index.')
    mode.add_argument('--find', metavar='TEXT', action='append', help='Find existing notes by behavior, symbol or clause ID; repeat for one shared read-only lookup.')
    mode.add_argument('--show', metavar='ID', help='Show an exact note, symbol or clause ID; read only.')
    parser.add_argument('--limit', type=int, choices=range(1, 21), default=5)
    parser.add_argument('--kind', choices=['operation', 'foundation', 'route'], help='Restrict --find to one note kind.')
    parser.add_argument('--section', metavar='HEADING', help='With --show, read only one exact note heading and its subsections.')
    args = parser.parse_args()
    if args.kind is not None and args.find is None:
        parser.error('--kind requires --find.')
    if args.section is not None and args.show is None:
        parser.error('--section requires --show.')
    if args.index:
        result = refresh_reuse_index(ROOT)
    elif args.navigation or args.find is not None or args.show is not None:
        import reuse_navigation as navigation
        try:
            if args.navigation:
                result = navigation.refresh(ROOT)
            else:
                notes = navigation.load(ROOT)
                if args.find is None:
                    result = navigation.describe(ROOT, notes, args.show, args.limit, args.section)
                elif len(args.find) == 1:
                    result = navigation.find(ROOT, notes, args.find[0], args.limit, args.kind)
                else:
                    documents = {}
                    result = [{'query': query, 'results': navigation.find(
                        ROOT, notes, query, args.limit, args.kind, _documents=documents)}
                        for query in args.find]
        except ValueError as exc:
            parser.error(str(exc))
    else:
        result = build()
    print(json.dumps(result, ensure_ascii=False, indent=2))
